        mods = tree["children"]
        cases = sum(1 for m in mods for s in (m.get("children") or []))
        api_cases = sum(1 for m in mods if "【接口】" in m["title"] for s in (m.get("children") or []))
        return len(mods), cases, cases - api_cases, api_cases, count_nodes(tree)

