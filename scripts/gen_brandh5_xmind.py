def L(title, children=None):
    node = {"title": title}
    if children:
        node["children"] = children
    return node


def merge_layers(prd_tree, api_tree):
    """接口层大类接在 PRD 大类之后、悬挂项之前，全树大类重新编号"""
    def strip_no(title):
        return re.sub(r"^\d+\.", "", title)

    prd_mods = list(prd_tree["children"])
    body = [m for m in prd_mods if HANG_KEYWORD not in m["title"]]
    hang = [m for m in prd_mods if HANG_KEYWORD in m["title"]]
    api_mods = [dict(m, title=API_PREFIX + strip_no(m["title"])) for m in api_tree["children"]]

    merged = body + api_mods + hang
    for i, mod in enumerate(merged, 1):
        mod["title"] = f"{i}.{strip_no(mod['title'])}"
    return {"title": prd_tree["title"], "children": merged}


