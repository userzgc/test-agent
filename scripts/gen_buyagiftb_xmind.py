def main():
    out_dir = os.path.join(os.path.dirname(__file__), '..', '..', 'docs', 'test-cases')
    out_dir = os.path.abspath(out_dir)

    # 完整版
    full_json = "/tmp/buyagiftb_full_tree.json"
    with open(full_json, "w", encoding="utf-8") as f:
        json.dump(full_tree, f, ensure_ascii=False, indent=2)
    full_xmind = os.path.join(out_dir, "买A赠B二期_测试用例.xmind")
    generate_xmind(full_tree, full_xmind)

    # 冒烟版
    smoke_json = "/tmp/buyagiftb_smoke_tree.json"
    with open(smoke_json, "w", encoding="utf-8") as f:
        json.dump(smoke_tree, f, ensure_ascii=False, indent=2)
    smoke_xmind = os.path.join(out_dir, "买A赠B二期_冒烟用例.xmind")
    generate_xmind(smoke_tree, smoke_xmind)

    # 统计
    def count_nodes(node, depth=0):
        children = node.get("children") or []
        total = 1
        for c in children:
            total += count_nodes(c, depth+1)
        return total
    full_cases = sum(1 for m in full_tree["children"] for s in (m.get("children") or []))
    smoke_cases = sum(1 for m in smoke_tree["children"] for s in (m.get("children") or []))
    print(f"完整版XMind: {full_xmind}")
    print(f"  模块数: {len(full_tree['children'])}，场景数: {full_cases}，总节点: {count_nodes(full_tree)}")
    print(f"冒烟版XMind: {smoke_xmind}")
    print(f"  模块数: {len(smoke_tree['children'])}，场景数: {smoke_cases}，总节点: {count_nodes(smoke_tree)}")

if __name__ == "__main__":
    main()
